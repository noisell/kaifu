export function language<T extends Worlds>(world: T) {
    const dictionary = a.find((l) => l.world === world)
    if (!dictionary) return world
    if (typeof window === 'undefined' || typeof localStorage === 'undefined') return world;
    const userLanguage = localStorage.getItem("language") as Languages | null
    if (!userLanguage || userLanguage === "en") return world
    const translate = dictionary.translations.find((l) => l.lang === userLanguage)?.translation
    if (!translate) return world
    return translate
}